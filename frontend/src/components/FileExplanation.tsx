import { useExplainFile } from '../hooks/useExplainFile'
import { getErrorMessage } from '../services/client'
import { ErrorMessage } from './ErrorMessage'

export const PRIVACY_NOTICE = "Sends this file's content to Anthropic to generate an explanation."

interface FileExplanationProps {
  projectId: string
  repositoryId: string
  path: string
}

function tokens(value: number | null): string {
  return value === null ? '—' : String(value)
}

/**
 * On-demand AI explanation of the displayed file. Requests happen only when the button is
 * clicked. The model's output is untrusted: it is rendered only as React text.
 */
export function FileExplanation({ projectId, repositoryId, path }: FileExplanationProps) {
  const explain = useExplainFile(projectId, repositoryId)
  const result = explain.data
  return (
    <section className="space-y-2 rounded-lg border border-slate-800 p-3" aria-label="File explanation">
      <div className="flex flex-wrap items-center gap-3">
        <button
          type="button"
          disabled={explain.isPending}
          onClick={() => explain.mutate(path)}
          className="rounded-lg bg-indigo-500 px-3 py-1.5 text-sm font-medium text-white hover:bg-indigo-400 disabled:cursor-not-allowed disabled:opacity-50"
        >
          Explain this file
        </button>
        <span className="text-xs text-slate-500">{PRIVACY_NOTICE}</span>
      </div>
      {explain.isPending && <p className="text-sm text-slate-400">Generating explanation…</p>}
      {explain.isError && (
        <ErrorMessage message={getErrorMessage(explain.error, 'Could not explain the file')} />
      )}
      {result && !explain.isPending && (
        <div className="space-y-1">
          <div className="whitespace-pre-wrap text-sm leading-6 text-slate-200" data-testid="explanation-text">
            {result.explanation}
          </div>
          <p className="text-xs text-slate-500">
            {`Generated by ${result.model} · ${tokens(result.input_tokens)} input / ${tokens(result.output_tokens)} output tokens`}
          </p>
        </div>
      )}
    </section>
  )
}
